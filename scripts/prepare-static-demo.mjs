/**
 * Rewrites the app for the GitHub Pages demo build, then exits. Run ONLY in
 * CI, against a throwaway checkout — it edits files in place and the result
 * must never be committed.
 *
 *   node scripts/prepare-static-demo.mjs
 *
 * Static hosting can't do any of the following, so each is removed rather
 * than left to fail the build:
 *
 *   1. API routes        — no server to run them (sync + GHL webhook).
 *   2. force-dynamic     — asks for per-request rendering; export needs
 *                          pages resolved at build time.
 *   3. redirect() at "/" — a real HTTP redirect needs a server; replaced
 *                          with a meta-refresh page.
 *
 * The pages themselves need no changes: loadPipelineData() already falls
 * back to mock data when no database is reachable, so the export bakes
 * that mock data into the HTML.
 */
import { readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Refuse to run outside CI without an explicit override.
 *
 * This script deletes app/api, proxy.ts and app/login, and rewrites page
 * files in place. Running it against a working tree destroys uncommitted
 * work, and `git checkout` cannot undo it for files that are not yet tracked
 * — which is exactly how the password gate and two page configs were lost
 * once already. Test the static build against a copy, not your checkout.
 */
if (!process.env.CI && process.env.ALLOW_DESTRUCTIVE_STATIC_PREP !== "true") {
  console.error(
    "Refusing to run: this rewrites and deletes files in place.\n" +
      "It is meant for CI against a throwaway checkout.\n\n" +
      "To test the static build locally, copy the repo first:\n" +
      "  git archive --format=tar HEAD | (mkdir -p /tmp/demo && tar -x -C /tmp/demo)\n\n" +
      "Or, if you really mean to mutate this checkout:\n" +
      "  ALLOW_DESTRUCTIVE_STATIC_PREP=true node scripts/prepare-static-demo.mjs"
  );
  process.exit(1);
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) out.push(...walk(path));
    else out.push(path);
  }
  return out;
}

// 1. Drop API routes.
rmSync("app/api", { recursive: true, force: true });
console.log("removed app/api (no server on GitHub Pages)");

// 1b. Drop the password gate and login screen. Static export has no server to
// run proxy.ts, and the demo contains only mock data so it needs no gate.
rmSync("proxy.ts", { force: true });
rmSync("app/login", { recursive: true, force: true });
console.log("removed proxy.ts + app/login (mock-data demo needs no gate)");

// 2. Make every page statically renderable.
let rewritten = 0;
for (const file of walk("app")) {
  if (!file.endsWith(".tsx") && !file.endsWith(".ts")) continue;
  const source = readFileSync(file, "utf8");
  if (!source.includes('export const dynamic = "force-dynamic"')) continue;
  writeFileSync(
    file,
    source.replace(
      'export const dynamic = "force-dynamic"',
      'export const dynamic = "force-static"'
    )
  );
  rewritten++;
}
console.log(`rewrote force-dynamic -> force-static in ${rewritten} file(s)`);

// 3. Replace the server redirect at "/" with a client-side one.
// The page renders inside app/layout.tsx, which already supplies <html>
// and <body>, so this must be a fragment. next/navigation's router
// applies basePath itself, so the path stays relative here.
writeFileSync(
  "app/page.tsx",
  `"use client";

// Generated by scripts/prepare-static-demo.mjs — the real app uses
// redirect(), which needs a server. Static hosts redirect in the browser.
import { useEffect } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";

export default function Home() {
  const router = useRouter();
  useEffect(() => {
    router.replace("/dashboard");
  }, [router]);

  return (
    <div className="p-6 text-sm">
      <Link href="/dashboard">Continue to the dashboard</Link>
    </div>
  );
}
`
);
console.log("replaced app/page.tsx redirect with a client-side redirect");
